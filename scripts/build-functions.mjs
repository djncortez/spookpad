// Bundles each packages/functions/src/entries/<name>.ts (with @spookpad/core and npm packages) into
// supabase/functions/<name>/bundle.mjs, which that function's index.ts serves with Deno.serve.
// Bundles are generated (gitignored): run this before every deploy (npm run deploy:functions does).
import { build } from "esbuild";
import { existsSync, readdirSync } from "node:fs";
import path from "node:path";

const ENTRIES = path.join("packages", "functions", "src", "entries");

for (const file of readdirSync(ENTRIES).filter((f) => f.endsWith(".ts"))) {
  const name = file.slice(0, -3);
  const dir = path.join("supabase", "functions", name);
  if (!existsSync(path.join(dir, "index.ts"))) throw new Error(`supabase/functions/${name}/index.ts is missing`);
  await build({
    entryPoints: [path.join(ENTRIES, file)],
    outfile: path.join(dir, "bundle.mjs"),
    bundle: true,
    platform: "browser", // Web APIs only (fetch, crypto.subtle): the same in Deno and in Node tests
    format: "esm",
    target: "es2022",
    legalComments: "none",
    banner: { js: `// GENERATED by scripts/build-functions.mjs from packages/functions/src/entries/${file}. Do not edit.` },
    logLevel: "warning",
  });
  console.log(`built supabase/functions/${name}/bundle.mjs`);
}
